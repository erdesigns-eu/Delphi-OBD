"""Reproduce the general vector icon unit from the standalone JSON source."""
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
CODES = {'line':1,'loop':2,'fill':3,'arc':4,'ring':5,'disc':6,'pie':7,'ellipse':8,'knock':9,'ink':10}
def encode(prims):
    result=[]
    for kind,*args in prims:
        result.append(CODES[kind])
        if kind in ('knock','ink'):result.extend(encode([args[0]]))
        elif kind in ('line','loop','fill'):
            result.append(len(args[0]))
            result.extend(value for point in args[0] for value in point)
        else:result.extend(args)
    return result
def build():
    source=json.loads((ROOT/'assets/icons.json').read_text())
    data=[];starts=[]
    for name,prims in source['icons']:
        starts.append(len(data));data.extend(encode(prims))
    starts.append(len(data))
    lines=['// Generated by tools/build_icons.py; general application icons.', 'unit ERD.Components.IconData;', 'interface', 'const']
    lines += [f'  ERD_ICON_{name.upper()} = {value};' for name,value in CODES.items()]
    lines += [f"  ERD_ICON_SHELL_FIRST = {source['shell_first']};",f"  ERD_ICON_STATUS_FIRST = {source['status_first']};",f"  ERD_ICON_COUNT = {len(source['icons'])};"]
    lines += [f'  ERD_ICON_START: array[0..{len(starts)-1}] of Integer = (', *['    '+', '.join(map(str,starts[i:i+16]))+(',' if i+16<len(starts) else ');') for i in range(0,len(starts),16)]]
    lines += [f'  ERD_ICON_DATA: array[0..{len(data)-1}] of Single = (']
    for i in range(0,len(data),16):lines.append('    '+', '.join(str(v) for v in data[i:i+16])+(',' if i+16<len(data) else ');'))
    lines += ['implementation','end.']
    return ('\r\n'.join(lines)+'\r\n').encode()
if __name__=='__main__':(ROOT/'src/UI/ERD.Components.IconData.pas').write_bytes(build())


def symbol(icon):
    import re, unicodedata
    label=unicodedata.normalize('NFKD',icon['label']).encode('ascii','ignore').decode()
    return 'ei%03d%s' % (icon['id'], ''.join(re.findall(r'[A-Za-z0-9]+', label)))


def build_catalog():
    import catalog_vectors
    catalog=json.loads((ROOT/'docs/iconset-catalog.json').read_text())
    lines=['// Generated by tools/build_icons.py; stable catalog IDs.', 'unit ERD.Components.IconCatalog;',
           '{$IFDEF FPC}{$MODE DELPHI}{$H+}{$CODEPAGE UTF8}{$ENDIF}', 'interface',
           'uses {$IFDEF FPC}SysUtils{$ELSE}System.SysUtils{$ENDIF};', 'type',
           '  TERDIconId = (eiNone,']
    for n,i in enumerate(catalog['icons']):lines.append('    '+symbol(i)+(',' if n+1<len(catalog['icons']) else ');'))
    lines += ['const',f"  ERD_CATALOG_COUNT = {catalog['count']};",
              '  ERD_ICON_NAMES: array[TERDIconId] of string = (',"    'None',"]
    for n,i in enumerate(catalog['icons']):lines.append("    '"+i['label'].replace("'","''")+"'"+(',' if n+1<len(catalog['icons']) else ');'))
    lines += ['implementation','end.']
    (ROOT/'src/UI/ERD.Components.IconCatalog.pas').write_bytes(b'\xef\xbb\xbf'+('\r\n'.join(lines)+'\r\n').encode())
    # Add production catalog to the small glyph vocabulary used for chrome.
    original=json.loads((ROOT/'assets/icons.json').read_text())
    original['catalog_first']=len(original['icons'])
    original['icons'] += [(symbol(i),catalog_vectors.vectors(i['id'])) for i in catalog['icons']]
    return original


def build_production():
    source=build_catalog();data=[];starts=[]
    for name,prims in source['icons']:
        starts.append(len(data));data.extend(encode(prims))
    starts.append(len(data))
    lines=['// Generated by tools/build_icons.py; do not edit.', 'unit ERD.Components.IconData;', 'interface','const']
    lines += [f'  ERD_ICON_{name.upper()} = {value};' for name,value in CODES.items()]
    for name in ['shell_first','status_first','catalog_first']:lines.append(f"  ERD_ICON_{name.upper()} = {source[name]};")
    lines += [f"  ERD_ICON_COUNT = {len(source['icons'])};",f'  ERD_ICON_START: array[0..{len(starts)-1}] of Integer = (', *['    '+', '.join(map(str,starts[i:i+16]))+(',' if i+16<len(starts) else ');') for i in range(0,len(starts),16)],f'  ERD_ICON_DATA: array[0..{len(data)-1}] of Single = (']
    for i in range(0,len(data),16):lines.append('    '+', '.join(str(round(v,4)) for v in data[i:i+16])+(',' if i+16<len(data) else ');'))
    lines += ['implementation','end.']
    (ROOT/'src/UI/ERD.Components.IconData.pas').write_bytes(b'\xef\xbb\xbf'+('\r\n'.join(lines)+'\r\n').encode())
    return source

if __name__=='__main__':build_production()
